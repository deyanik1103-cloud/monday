def variants(q):
    return {q, q.lower(), q.rstrip("?.!")}


def build():
    examples = set()
    for questions, answers in ENTRIES:
        for q in questions:
            for v in variants(q):
                for a in answers:
                    a = a.replace("{CREATOR}", CREATOR)
                    examples.add(f"<|user|>{v}<|assistant|>{a}<|end|>\n")
    examples = sorted(examples)
    random.Random(42).shuffle(examples)
    return examples


if __name__ == "__main__":
    ex = build()
    with open("data/chat.txt", "w", encoding="utf-8") as f:
        f.write("".join(ex))
    print(f"Wrote data/chat.txt with {len(ex)} examples from {len(ENTRIES)} topics.")
